/**
 * `jev-models ladder-agents`: write one general-purpose-clone subagent definition per ladder step of the model catalogue.
 *
 * The Agent tool's `model` accepts only the aliases (`sonnet`, `opus`, `haiku`, `fable`), so a version inside an alias
 * (`claude-sonnet-5` while `sonnet` is `claude-sonnet-5-5`) can be chosen only through a subagent definition whose front
 * matter pins a full model id. These files are those definitions: `jev-ladder-<id>.md`, no `tools` field (so the agent
 * inherits every tool, like `general-purpose`). Nothing is installed by Jev on its own: the command writes into the
 * directory it is given with `--dir` and into no other.
 *
 * Self-contained: it reads the catalogue (cache file, no network) and the user's overrides, nothing else.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { ladder, loadCatalogue, loadOverrides, type Catalogue, type CatalogueTier, type ModelOverrides } from '../core/catalogue.js';

/** First line of the body of every file this command writes; an existing file without it is never overwritten. */
export const GENERATED_MARKER = '<!-- generated by jev-models ladder-agents; regenerate rather than edit -->';

/** The subagent name for a model id: `jev-ladder-` plus the id lowercased, anything but letters, digits and hyphens turned into a hyphen. */
export function ladderDefName(id: string): string {
  return `jev-ladder-${id.toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '')}`;
}

export interface LadderAgentFile {
  /** The model id the definition pins. */
  id: string;
  /** The subagent name (`jev-ladder-<id>`). */
  name: string;
  /** File name inside the target directory. */
  file: string;
  content: string;
}

const ALL_TIERS: readonly CatalogueTier[] = ['free', 'cheap', 'standard', 'deep'];

/** Every ladder step of the catalogue, cheapest tier first, strongest first inside a tier; `maxTier` leaves out the tiers above it (default: all). */
export function ladderIds(cat: Catalogue | null | undefined, overrides?: ModelOverrides, maxTier?: CatalogueTier): string[] {
  const tiers = maxTier ? ALL_TIERS.slice(0, ALL_TIERS.indexOf(maxTier) + 1) : ALL_TIERS;
  return [...new Set(tiers.flatMap((t) => ladder(cat, t, overrides)))];
}

/** Pure: the definition files for a catalogue, one per ladder step (up to `maxTier`). An id that cannot be a plain file name is left out. */
export function ladderAgentFiles(cat: Catalogue | null | undefined, overrides?: ModelOverrides, maxTier?: CatalogueTier): LadderAgentFile[] {
  const out: LadderAgentFile[] = [];
  for (const id of ladderIds(cat, overrides, maxTier)) {
    // The model id goes into front matter unquoted: only the characters a Claude model id has.
    if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(id)) continue;
    const name = ladderDefName(id);
    const content =
      `---\n` +
      `name: ${name}\n` +
      `description: General-purpose agent pinned to ${id}, a step of the Jev model ladder. Inherits all tools. Generated by jev-models ladder-agents.\n` +
      `model: ${id}\n` +
      `---\n` +
      `${GENERATED_MARKER}\n\n` +
      `You are a general-purpose agent. Complete the task you are given fully, using the tools available to you, and report ` +
      `the result accurately and concisely. If the task cannot be completed, say what is missing.\n`;
    out.push({ id, name, file: `${name}.md`, content });
  }
  return out;
}

export interface WriteLadderResult {
  written: string[];
  /** Files left alone because they exist and were not generated by this command, or could not be written. */
  skipped: Array<{ file: string; reason: string }>;
}

/** Write the definitions into `dir` (created when missing). An existing file that does not carry the generated marker is skipped, never overwritten. */
export function writeLadderAgents(dir: string, files: readonly LadderAgentFile[]): WriteLadderResult {
  const result: WriteLadderResult = { written: [], skipped: [] };
  fs.mkdirSync(dir, { recursive: true });
  for (const f of files) {
    const target = path.join(dir, f.file);
    try {
      if (fs.existsSync(target) && !fs.readFileSync(target, 'utf8').includes(GENERATED_MARKER)) {
        result.skipped.push({ file: target, reason: 'exists and was not generated by ladder-agents' });
        continue;
      }
      fs.writeFileSync(target, f.content, 'utf8');
      result.written.push(target);
    } catch (err) {
      result.skipped.push({ file: target, reason: (err as Error).message });
    }
  }
  return result;
}

export const LADDER_AGENTS_USAGE =
  'usage: jev-models ladder-agents --dir <directory> [--harness claude-code] [--max-tier free|cheap|standard|deep]\n' +
  '  Writes jev-ladder-<id>.md (a general-purpose clone pinned to one ladder model id, tools inherited) per ladder step\n' +
  '  of the model catalogue into <directory>. It writes nowhere without --dir and installs nothing by itself.\n' +
  '  --max-tier skips the steps above that tier (default: no cap); `standard` writes no opus or fable definition.';

/** The value of `--name value` or `--name=value`; undefined when absent, null when the flag has no value. */
function flag(argv: readonly string[], name: string): string | null | undefined {
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === name) {
      const v = argv[i + 1];
      return v === undefined || v.startsWith('--') ? null : v;
    }
    if (a.startsWith(`${name}=`)) return a.slice(name.length + 1) || null;
  }
  return undefined;
}

export interface CliIo {
  out: (line: string) => void;
  err: (line: string) => void;
}

/**
 * The command. Exit codes: 0 done (also when some files were skipped, which is listed), 1 no usable catalogue, 2 bad
 * arguments (`--dir` missing: nothing is written).
 * Hidden flag `--catalogue-dir <dir>` reads the catalogue from a directory other than `~/.config/jev/models` (tests).
 */
export function runLadderAgents(argv: readonly string[], io: CliIo = { out: console.log, err: console.error }): number {
  const dir = flag(argv, '--dir');
  if (!dir) {
    io.err('ladder-agents needs --dir <directory>; nothing was written.');
    io.err(LADDER_AGENTS_USAGE);
    return 2;
  }
  const maxTierFlag = flag(argv, '--max-tier');
  if (maxTierFlag !== undefined && !(ALL_TIERS as readonly string[]).includes(maxTierFlag ?? '')) {
    io.err(`ladder-agents: --max-tier must be one of ${ALL_TIERS.join(', ')}; nothing was written.`);
    io.err(LADDER_AGENTS_USAGE);
    return 2;
  }
  const maxTier = maxTierFlag as CatalogueTier | undefined;
  const harness = flag(argv, '--harness') ?? 'claude-code';
  const catDir = flag(argv, '--catalogue-dir') ?? undefined;
  const cat = loadCatalogue(harness, catDir);
  const files = ladderAgentFiles(cat, cat ? loadOverrides() : undefined, maxTier);
  if (!cat || files.length === 0) {
    io.err(`ladder-agents: no usable catalogue for harness "${harness}" (or no ladder step in it). Refresh the catalogue first; nothing was written.`);
    return 1;
  }
  const result = writeLadderAgents(path.resolve(dir), files);
  for (const f of result.written) io.out(`wrote ${f}`);
  for (const s of result.skipped) io.err(`skipped ${s.file}: ${s.reason}`);
  io.out(`${result.written.length} written, ${result.skipped.length} skipped. Agents are addressed by name (jev-ladder-<id>); Claude Code loads them from the directory you chose.`);
  return 0;
}
